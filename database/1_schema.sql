-- USERS table
CREATE TABLE USERS (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(50) NOT NULL UNIQUE,
    password VARCHAR2(255) NOT NULL,
    role VARCHAR2(20) NOT NULL,
    CHECK (role IN ('ADMIN', 'REQUESTER', 'ORGANISATION'))
);

-- ORGANISATIONS table
CREATE TABLE ORGANISATIONS (
    org_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL UNIQUE,
    org_name VARCHAR2(100) NOT NULL,
    org_type VARCHAR2(20) NOT NULL,
    city VARCHAR2(50) NOT NULL,
    verification_status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    FOREIGN KEY (user_id) REFERENCES USERS(user_id),
    CHECK (org_type IN ('NGO', 'HOSPITAL')),
    CHECK (verification_status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

-- BLOOD_GROUPS table
CREATE TABLE BLOOD_GROUPS (
    blood_group_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blood_group_name VARCHAR2(5) NOT NULL UNIQUE
);

-- INVENTORY table
CREATE TABLE INVENTORY (
    inventory_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id NUMBER NOT NULL,
    blood_group_id NUMBER NOT NULL,
    units_available NUMBER DEFAULT 0 NOT NULL,
    last_updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (org_id) REFERENCES ORGANISATIONS(org_id),
    FOREIGN KEY (blood_group_id) REFERENCES BLOOD_GROUPS(blood_group_id),
    UNIQUE (org_id, blood_group_id),
    CHECK (units_available >= 0)
);

-- BLOOD_REQUESTS table
CREATE TABLE BLOOD_REQUESTS (
    request_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id NUMBER NOT NULL,
    blood_group_id NUMBER NOT NULL,
    units_required NUMBER NOT NULL,
    city VARCHAR2(50) NOT NULL,
    urgency VARCHAR2(20) DEFAULT 'NORMAL' NOT NULL,
    request_status VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    selected_response_id NUMBER,
    FOREIGN KEY (requester_id) REFERENCES USERS(user_id),
    FOREIGN KEY (blood_group_id) REFERENCES BLOOD_GROUPS(blood_group_id),
    CHECK (units_required > 0),
    CHECK (urgency IN ('NORMAL', 'URGENT', 'EMERGENCY')),
    CHECK (request_status IN ('OPEN', 'MATCHED', 'IN_PROGRESS', 'FULFILLED', 'CANCELLED'))
);

-- REQUEST_RESPONSES table
CREATE TABLE REQUEST_RESPONSES (
    response_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id NUMBER NOT NULL,
    org_id NUMBER NOT NULL,
    units_offered NUMBER DEFAULT 0 NOT NULL,
    response_status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    message VARCHAR2(255),
    FOREIGN KEY (request_id) REFERENCES BLOOD_REQUESTS(request_id),
    FOREIGN KEY (org_id) REFERENCES ORGANISATIONS(org_id),
    UNIQUE (request_id, org_id),
    CHECK (units_offered >= 0),
    CHECK (response_status IN ('PENDING', 'ACCEPTED', 'PARTIAL', 'DECLINED', 'SELECTED', 'COMPLETED'))
);

